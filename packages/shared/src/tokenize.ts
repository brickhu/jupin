/**
 * ⭐ **切词规则的唯一实现** —— 全仓库只允许这一处。
 *
 * 规则：按空白切、丢掉空段。**不做**去标点 / 小写 / 词形还原 ——
 * 它不是自然语言分词，是「一个朗读单元里第 i 个 token 是谁」。
 *
 * ⚠️⚠️ 为什么必须只有一处：这个下标同时被**四个角色**使用 ——
 *    · 内容流水线的词级切片与时间戳（tools/pipeline）
 *    · 服务端拼逐词音频路径（routes/articles.ts）
 *    · 客户端点词播放（页面上第 i 个词 ↔ 第 i 个音频/区间）
 *    · 端侧逐词上色（alignWordScores）
 *    只要有一处用了别的规则（比如顺手去掉标点），**下标就会整体错位** ——
 *    点第 3 个词听到第 4 个词，而界面上完全看不出（都是正常发音，只是不对应）。
 *    而且客户端只在「条数相等」时才启用点词播放（见 reading.ts 的 wordTimes），
 *    规则一漂就**静默**退化成切片播放 —— 更难发现。
 *
 * ⚠️ 标点**属于它前面的词**（"days," 是一个 token，不是 "days"）。
 */
export function plainWordsOf(text: string): string[] {
  return String(text ?? '').split(/\s+/).filter(Boolean)
}
