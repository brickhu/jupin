/**
 * ⭐ 录音参数 —— 「压缩」和「有麦克风帧」这两个要求的**唯一交集是 mp3**。
 *
 * ⚠️ 三个候选，差别是官方文档写死的（见 docs/research/miniprogram-api-constraints.md）：
 *
 *   | format | 体积（20 秒） | `frameSize` 帧回调 | 结论 |
 *   | --- | --- | --- | --- |
 *   | pcm | ~640KB | ✅ 有帧 | 波形能做，但体积太大 |
 *   | aac | ~120KB | ❌ 「暂仅支持 mp3、pcm」 | 体积小，但**波形没有数据源** |
 *   | **mp3** | **~120KB** | ✅ 有帧 | **两个都要，选它** |
 *
 * ⚠️⚠️ 为什么不能只看「接口默认值是 aac」：默认值确实最稳，但 aac 会
 *    直接把实时波形这条路堵死（一帧都收不到）。而波形回答的是
 *    「麦克风到底收到我的声音没有」—— 那是录音阶段用户唯一能自查的问题，
 *    不能为了省事把它丢掉。mp3 是同为压缩格式、又在帧回调支持名单里的那个。
 *
 * ⭐ 附带的好处：上传上来的 mp3 **本身就是存档** ——
 *    服务端不转码、不再存第二份（见 services/recording.ts），
 *    结果页的「试听」也不用再拿帧拼 WAV（mp3 两个平台都能直接播）。
 *
 * ⚠️ 剩下的唯一未知：mp3 模式下帧给的到底是**原始 PCM** 还是**压缩块**。
 *    这一条至今没在真机上验过，所以代码按**实际内容**判断（见朗读页的帧分类）：
 *    是 PCM 就照常画波形；不是就把波形换成「录音中」提示 ——
 *    绝不拿压缩字节当振幅画一条骗人的柱子（这个坑本项目踩过，见
 *    docs/research/recorder-output-formats.md 的「文件 ≠ 帧」）。
 */
export const RECORD_SPEC = {
  /** 压缩 + 有帧回调的唯一交集（aac 没有帧，pcm 体积太大） */
  format: 'mp3',
  /** 16000Hz 的合法区间是 24000~96000；48000 是接口默认码率 */
  encodeBitRate: 48_000,
  /** 上传路径的兜底后缀（真实后缀优先按落盘文件的扩展名，见 lib/api/upload.ts） */
  extension: 'mp3',
  /** 这个格式下 onFrameRecorded 会不会给麦克风帧（决定朗读页画不画实时波形） */
  frames: true,
  /**
   * 帧大小（KB，必须是整数）—— **只影响实时波形多久更新一次**。
   * ⚠️ 与 AUDIO_SPEC.frameSizeKb（那是旧 PCM 链路的请求值）分开：
   *    mp3 下 1KB ≈ 170ms 音频，2KB 就是 ~340ms —— 后者波形明显发顿。
   */
  frameSizeKb: 1,
} as const

/**
 * ⭐ 录音**存档**格式 —— 只有**不是压缩格式的那些**才需要它。
 *
 * ⚠️ 用 RECORD_SPEC 录出来的 aac 本身就是压缩的，直接当存档用；
 *    这一条只在遇到「裸 PCM / WebM」时才生效（老客户端、老记录）。
 *    见 services/recording.ts 的 archiveRecording。
 *
 * ⚠️ 它和 AUDIO_SPEC 是两件事，别混：
 *    · AUDIO_SPEC —— 喂给引擎的规格（16k/16bit/单声道裸 PCM），**必须无损**；
 *    · 这一条     —— 存档，只要够听清，越小越好（mp3 32kbps ≈ 电话音质）。
 *
 * ⚠️ **打分不受压缩影响**：引擎拿到的是上传后立刻解码出的 16k PCM，
 *    存档是**打分之后**才生成的那一份。
 */
export const STORED_AUDIO_FALLBACK = {
  ext: 'mp3',
  mime: 'audio/mpeg',
  bitrateKbps: 32,
} as const

