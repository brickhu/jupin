/** 征服阈值：竞技场得分 ≥ 此值即「征服」，永久保留 */
export const CONQUEST_THRESHOLD = 85

/**
 * ⭐ 挑战额度 —— **每人每天几次，与句子无关**。
 *
 * ⚠️⚠️ 这条规则前后换过两次，两次都是因为"用户讲不清"：
 *     ① 「每 24 小时滚动冷却」—— 回答的是"你多久没来了"，
 *        用户撞上它时明明昨天刚读过，却要等满 24 小时；
 *     ② 「每句 N 次 + 2 分钟间隔」—— 每换一句就换一个数，
 *        "这句还能读几次"要一句句记，而 2 分钟间隔还专挑他正想练的时候拦。
 *     现在只剩一句：**今天还剩几次**。明天会回来，可预期，也说得清。
 *
 * ⚠️ 付费用户那 50 次是**硬上限**，不是"无限"：脚本刷分同样要拦。
 */
/** 免费用户每天可挑战的次数 */
export const FREE_DAILY_CHALLENGES = 1
/** 付费用户每天的硬上限 */
export const MEMBER_DAILY_CHALLENGES = 50

/** 每日无效提交上限（超过则当天暂停提交） */
export const MAX_INVALID_PER_DAY = 3

/** 本地预检阈值 —— 一律极度宽松：放行垃圾的成本极低，误伤用户的成本是流失 */
export const PREFLIGHT = {
  /** 录音最短时长（毫秒）—— 低于此值判定为技术无效 */
  minDurationMs: 1500,
  /** 英语正常朗读语速（词/分钟），用于估算预期语音时长 */
  wpm: 150,
} as const

/** 单词发音时间估算（毫秒/词） */
export const MS_PER_WORD = 60_000 / PREFLIGHT.wpm

/** 单次评测的音频格式要求（讯飞 ISE 硬要求，不符会被判「乱读」） */
export const AUDIO_SPEC = {
  sampleRate: 16_000,
  bitDepth: 16,
  channels: 1,
  /**
   * 分析帧的采样数（1024 = 64ms）。
   * ⭐ 它与「录音 API 每次回调给多大一块」是**两个概念**，刻意解耦：
   *    回调帧多大由设备决定（实测 iPhone 请求 2KB 却给 4096 字节），
   *    需要固定长度分析时一律按这个值重新切（见 frameAudio）。
   */
  frameSamples: 1024,

  // ----------------------------------------------------------------
  // ⚠️ 传给 RecorderManager.start({ frameSize }) 的**请求值**
  //
  //    单位 KB，必须是整数；官方限制「暂仅支持 mp3、pcm」，我们用 PCM。
  //
  //    ⛔ 这**不是契约**：实测 iPhone 15 / iOS 26 请求 2KB 却拿到 4096 字节。
  //       推测是设备原生音频缓冲（iOS 常见 2048 采样 = 4096 字节）比请求值大，被向上取整。
  //       Android 尚未实测。
  //
  //    ⚠️ 所以：**不要用它推任何期望值**。曾经因为拿它当真，把正常的 4096 字节帧
  //       误判成 T2 失败。判断音频是否正确要看「每秒字节数」（见真机自检 T3+T4）。
  // ----------------------------------------------------------------
  frameSizeKb: 2,
} as const

