/** 单次评测的音频格式要求（讯飞 ISE 硬要求，不符会被判「乱读」） */
export const AUDIO_SPEC = {
  sampleRate: 16_000,
  bitDepth: 16,
  channels: 1,
  // ----------------------------------------------------------------
  // ⭐ Worker 侧的**分析帧长** —— 这才是算法真正依赖的东西
  //
  //    它与「录音 API 每次回调给多大一块」是**两个概念**，刻意解耦：
  //    录音帧多大由设备决定（可能不被 frameSize 控制），
  //    而 Worker 会把攒到的 PCM 重新切成固定长度再分析。
  //
  //    选 1024 采样（64ms）的理由：
  //      · YIN 基频检测在 70Hz 下限需要 ≥2 个周期（≈457 采样），512 太勉强
  //      · 64ms 对 VAD 与进度追踪仍足够细
  // ----------------------------------------------------------------
  /** 分析帧的采样数 */
  frameSamples: 1024,
  /** 分析帧的字节数（1024 采样 × 2 字节） */
  frameBytes: 2048,
  /** 分析帧的时长（毫秒）= 1024 / 16000 × 1000 */
  frameMs: 64,

  // ----------------------------------------------------------------
  // ⚠️ 传给 RecorderManager.start({ frameSize }) 的**请求值**
  //
  //    单位 KB，必须是整数；官方限制「暂仅支持 mp3、pcm」，我们用 PCM。
  //
  //    ⛔ 这**不是契约**：实测 iPhone 15 / iOS 26 请求 2KB 却拿到 4096 字节。
  //       推测是设备原生音频缓冲（iOS 常见 2048 采样 = 4096 字节）比请求值大，被向上取整。
  //       Android 尚未实测。
  //
  //    ⚠️ 所以：**不要用它推任何期望值**。曾经因为拿它当真，把正常的 4096 字节帧
  //       误判成 T2 失败。判断音频是否正确要看「每秒字节数」（见真机自检 T3+T4）。
  // ----------------------------------------------------------------
  frameSizeKb: 2,
} as const

