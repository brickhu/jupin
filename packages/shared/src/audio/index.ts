/**
 * 端侧音频算法 —— 全部是纯函数，零平台依赖。
 *
 * ⭐ 设计约束：这些函数不得 import 任何小程序 / Node / 浏览器 API。
 *    原因：小程序里调试音频算法极其痛苦（无断点、难复现、日志要开 vConsole），
 *    做成纯函数就能在 Node 里用 vitest 快速迭代。
 *
 * ⚠️⚠️ 这里**已经没有实时逐词跟随**了（DTW / MFCC / VAD / 基频 全部删除）。
 *    原因是产品决策，不是技术故障：
 *      · 用 DTW 把用户音频对齐到参考音，本质是**间接代理** ——
 *        它只会回答「你的音频最像参考音的哪一段」，而**说不出「你读的是另一个词」**。
 *        你读成 an，它也必须给你找个对应的参考片段，于是"经过就算匹配"、最后全绿。
 *      · 业界做实时逐词标注的（Google Read Along 等）用的都是 **ASR**（端侧识别），
 *        而多邻国**刻意不做**实时跟随 —— 说完给判定。
 *      · 小程序主包 2MB，装不下端侧 ASR 模型；云端流式 ASR 每用户每次都在烧钱。
 *      ⇒ 结论：实时跟随摘掉，力气花在「说完之后的权威反馈」（讯飞 ISE）上。
 *
 *    保留下来的只有**录音链路必需**的三样：FFT / 重采样 / WAV 编解码。
 */
