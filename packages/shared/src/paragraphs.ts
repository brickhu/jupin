/**
 * ⭐ 把粘贴进来的英文切成**段落**（一段 = 一条朗读单元）。
 *
 * ⚠️⚠️ 拆分是**确定性**的（空行分隔），**不交给模型判**（2026-09 用户决定）。
 *    理由：模型判切分不稳定（同一段今天切两条、明天切一条），而「段数 = 条数」
 *    这件事必须可预期 —— 它还决定了要花几次 TTS。
 *    **接受因此出现超长句**：那是内容本身的问题，由人选文时把关，不由模型替我们切。
 *
 * ⚠️ 段内的单个换行当作**硬折行**（粘进来的文本常常是折过行的），归一成一个空格 ——
 *    否则同一句话会因为「有没有折行」算出两个不同的 id（内容寻址：id = sha256(text)）。
 *
 * ⚠️ 只做「切段 + 段内空白归一」：**不纠错、不去标点、不改大小写** —— 那是下一步 LLM 的事。
 */
export function splitParagraphs(input: string): string[] {
  return String(input ?? '')
    // 空行分段（行内允许有空白，Windows 的 \r\n 也认）
    .split(/\r?\n\s*\r?\n+/)
    // 段内：换行/制表/多空格一律归一成一个空格，再去首尾
    .map((p) => p.replace(/\s+/g, ' ').trim())
    .filter((p) => p !== '')
}
